"""Generate the People Playground mod's data from the sheets:
  ppg/StrayedSupplyCrate/Sheets.g.cs  one struct row per items row + the crate row
  ppg/StrayedSupplyCrate/thumb.png    the mod's own crate icon (original pixel art, not Strayed's)"""
import json, os, struct, zlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOD = os.path.join(ROOT, "ppg", "StrayedSupplyCrate")
load = lambda n: json.load(open(os.path.join(ROOT, "sheets", n + ".json"), encoding="utf-8"))
items, crate = load("items"), load("crate")

def s(v): return "null" if v is None else json.dumps(v)
def f(v): return "float.NaN" if v is None else f"{float(v)}f"

out = ["// <auto-generated> from sheets/*.json by tools/gen.py - edit the sheets, not this file.",
       "namespace StrayedSupplyCrate", "{",
       "    public struct ItemRow", "    {",
       "        public string Id, DisplayName, PpgBase, HoldKind;",
       "        public float StrayedDamage, LightRange, MassKg;",
       "        public ItemRow(string id, string name, string ppgBase, string hold, float strayedDamage, float light, float mass)",
       "        { Id = id; DisplayName = name; PpgBase = ppgBase; HoldKind = hold; StrayedDamage = strayedDamage; LightRange = light; MassKg = mass; }",
       "    }", "",
       "    public static class Sheets", "    {",
       "        public static readonly ItemRow[] Items =", "        {"]
for r in items["rows"]:
    out.append(f"            new ItemRow({s(r['id'])}, {s(r['displayName'])}, {s(r['ppgBase'])}, {s(r['holdKind'])}, "
               f"{f(r['strayedDamage'])}, {f(r['lightRange'])}, {f(r['massKg'])}),")
out.append("        };")
c = crate["rows"][0]
out += [f"        public const string CrateBase = {s(c['ppgBase'])};",
        f"        public static readonly float[] CrateOffset = {{ {', '.join(f(x) for x in c['offset'])} }};",
        f"        public static readonly string[] CrateContents = {{ {', '.join(s(x) for x in c['contents'])} }};",
        f"        public const bool CrateOncePerMap = {str(c['oncePerMap']).lower()};",
        "",
        "        public static ItemRow Find(string id)",
        "        {",
        "            foreach (var r in Items) if (r.Id == id) return r;",
        "            throw new System.ArgumentException(\"no items row \" + id);",
        "        }",
        "    }", "}", ""]
os.makedirs(MOD, exist_ok=True)
open(os.path.join(MOD, "Sheets.g.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(out))

# 32x32 wooden supply crate with metal corners and a brass plate, scaled x16 to 512x512
P = {".": (0, 0, 0, 0), "o": (38, 26, 16, 255), "w": (150, 98, 52, 255), "l": (186, 128, 72, 255),
     "d": (112, 72, 38, 255), "m": (128, 132, 138, 255), "s": (210, 160, 60, 255)}

def pixel(x, y):
    if x < 2 or x > 29 or y < 4 or y > 29: return "."
    if x in (2, 29) or y in (4, 29): return "o"
    corner = (x < 7 or x > 24) and (y < 9 or y > 24)
    if x in (3, 4, 27, 28) or y in (5, 6, 27, 28): return "m" if corner else "d"
    if abs((x - 3) - (y - 5)) <= 1 or abs((x - 3) - (28 - y)) <= 1: return "d"
    if 13 <= x <= 18 and 14 <= y <= 19: return "s" if 14 <= x <= 17 and 15 <= y <= 18 else "o"
    return "l" if (y - 7) % 5 == 0 else "w"

S = 16
raw = bytearray()
for y in range(32 * S):
    raw.append(0)
    for x in range(32 * S): raw += bytes(P[pixel(x // S, y // S)])
def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 32 * S, 32 * S, 8, 6, 0, 0, 0))
       + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))
open(os.path.join(MOD, "thumb.png"), "wb").write(png)
print("wrote ppg/StrayedSupplyCrate/Sheets.g.cs, thumb.png")
