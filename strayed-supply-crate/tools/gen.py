"""Generate src/StrayedSupply.Plugin/Generated/Sheets.g.cs from the sheets: one struct row per items row
plus the crate row."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
load = lambda n: json.load(open(os.path.join(ROOT, "sheets", n + ".json"), encoding="utf-8"))
items, crate = load("items"), load("crate")

def s(v): return "null" if v is None else json.dumps(v)
def f(v): return "float.NaN" if v is None else f"{float(v)}f"

out = ["// <auto-generated> from sheets/*.json by tools/gen.py - edit the sheets, not this file.",
       "namespace StrayedSupply.Plugin", "{",
       "    public readonly struct ItemRow", "    {",
       "        public readonly string Id, DisplayName, StrayedMesh, StrayedTexture, HoldKind;",
       "        public readonly float StrayedDamage, LengthM, LightRange, MassKg;",
       "        public ItemRow(string id, string name, string mesh, string tex, string hold, float sd, float length, float light, float mass)",
       "        { Id = id; DisplayName = name; StrayedMesh = mesh; StrayedTexture = tex; HoldKind = hold; StrayedDamage = sd; LengthM = length; LightRange = light; MassKg = mass; }",
       "    }", "",
       "    public static class Sheets", "    {",
       "        public static readonly ItemRow[] Items =", "        {"]
for r in items["rows"]:
    out.append(f"            new ItemRow({s(r['id'])}, {s(r['displayName'])}, {s(r['strayedMesh'])}, {s(r['strayedTexture'])}, {s(r['holdKind'])}, "
               f"{f(r['strayedDamage'])}, {f(r['lengthM'])}, {f(r['lightRange'])}, {f(r['massKg'])}),")
out.append("        };")
c = crate["rows"][0]
out += [f"        public const string CrateTexture = {s(c['strayedTexture'])};",
        f"        public static readonly float[] CrateOffset = {{ {', '.join(f(x) for x in c['offset'])} }};",
        f"        public static readonly string[] CrateContents = {{ {', '.join(s(x) for x in c['contents'])} }};",
        f"        public const bool CrateOncePerRun = {str(c['oncePerRun']).lower()};",
        "    }", "}", ""]
dst = os.path.join(ROOT, "src", "StrayedSupply.Plugin", "Generated", "Sheets.g.cs")
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote", os.path.relpath(dst, ROOT))
